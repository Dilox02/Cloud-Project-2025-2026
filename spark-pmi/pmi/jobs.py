import math
import re
from collections import defaultdict
from typing import List, Tuple

from pyspark import RDD, StorageLevel
from pyspark.broadcast import Broadcast #it allows to efficiently distribute a read variable across executors

from .config import JobConfig


# Matches any character that is not a lowercase letter or space (puntuaction, numbers).
# Keeps the token stream identical to the original Hadoop mapper implementation.
_NON_ALPHA = re.compile(r"[^a-z\s]")


# Converts line to lowercase, replaces non-alphabetic characters with spaces, and splits into words.
def tokenize(line: str) -> List[str]:
    return _NON_ALPHA.sub(" ", line.lower()).split()



class WordCountJob:
    """MR Job 1 — unigram counts and total token count N."""

    def __init__(self, config: JobConfig):
        self.config = config

    def run(self, lines: RDD) -> Tuple[RDD, int]: 
        counts = (
            lines.mapPartitions(_partition_word_counts) #instead of processing line by line with flatmap we use mapPartitions with an entire partition of lines as iterator
                 .reduceByKey(lambda a, b: a + b, numPartitions=self.config.num_partitions)#takes tuples generated by workers and aggregate them
                 .persist(StorageLevel.MEMORY_AND_DISK)  #it caches the data in memory or on disk (in case of spill) because it is used twice: sum() below + collectAsMap() in pipeline
        )
        # Replaces the __TOTAL__ token emitted by the Hadoop reducer.
        return counts, int(counts.values().sum())


class CooccurrenceJob:
    """MR Job 2 — co-occurrence pairs over a sliding ±window."""

    def __init__(self, config: JobConfig):
        self.config = config

    def run(self, lines: RDD) -> RDD:
        window = self.config.window_size
        return (
            lines.mapPartitions(lambda it: _partition_to_pairs(it, window))
                 .reduceByKey(lambda a, b: a + b, numPartitions=self.config.num_partitions)
        )


class PmiJob:
    """MR Job 3 — PMI(x,y) = log2(c(x,y) * N / (c(x) * c(y))), keeps PPMI >= 0."""

    def __init__(self, config: JobConfig):
        self.config = config

    def run(self, pairs: RDD, counts: Broadcast, total_tokens: int) -> RDD:
        return pairs.flatMap(lambda kv: _score_pair(kv, counts.value, total_tokens))#flatmap return 0 or 1 elements for each input element, so it's usefull to discard negative pmi

# Acts as an In-Mapper Combiner to aggregate word counts locally within each partition.
# Bounding unique keys at `flush_at` prevents Python worker OOMs, while local
# aggregation drastically reduces serialization overhead across the Python-JVM boundary.
def _partition_word_counts(lines, flush_at=200_000):
    local = defaultdict(int)
    for line in lines:
        for token in tokenize(line):
            local[token] += 1
        if len(local) >= flush_at:
            yield from local.items()
            local.clear()
    yield from local.items()


# Acts as an In-Mapper Combiner to aggregate word co-occurrence counts locally within each partition.
# Yields flat ((word_x, word_y), count) tuples instead of the whole dictionary.
# Memory is bounded at `flush_at` to prevent Python worker OOMs.
def _partition_to_pairs(lines, window, flush_at=50_000):
    local = defaultdict(int)
    for line in lines:
        tokens = tokenize(line)
        last = len(tokens) - 1
        for i, center in enumerate(tokens):
            for j in range(max(0, i - window), min(last, i + window) + 1):
                if j != i:
                    local[(center, tokens[j])] += 1
        if len(local) >= flush_at:
            yield from local.items()
            local.clear()
    yield from local.items()


def _score_pair(kv, counts, total_tokens):
    (word_x, word_y), cxy = kv #tuple unpacking to extract values from the tuple kv
    cx = counts.get(word_x)
    cy = counts.get(word_y)
    if not cx or not cy or total_tokens == 0:  # missing count or div by zero
        return
    pmi = math.log2(cxy * total_tokens / (cx * cy))
    if pmi >= 0:  # PPMI filter
        yield (word_x, word_y), pmi
